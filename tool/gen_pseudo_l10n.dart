// Generates test/helpers/pseudo_l10n.dart: an English AppLocalizations whose
// every string is about 40% longer (the stretch Russian, German or Turkish
// text needs), for the long-text layout tests.
//
//   flutter gen-l10n && dart run tool/gen_pseudo_l10n.dart
//
// Re-run after adding or removing ARB keys (a removed key fails to compile).
import 'dart:io';

void main() {
  final src = File('lib/l10n/app_localizations_en.dart').readAsLinesSync();
  final getter = RegExp(r'^  String get (\w+)\b');
  final method = RegExp(r'^  String (\w+)\(([^)]*)\)');
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_pseudo_l10n.dart. Do not edit by hand.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln("import 'package:screw_out/l10n/app_localizations_en.dart';")
    ..writeln()
    ..writeln("import 'pseudo_text.dart';")
    ..writeln()
    ..writeln('/// English, stretched by about 40% (see [stretch]).')
    ..writeln('class PseudoLongL10n extends AppLocalizationsEn {')
    ..writeln('  PseudoLongL10n([super.locale]);');
  var count = 0;
  for (final line in src) {
    final g = getter.firstMatch(line);
    if (g != null) {
      final n = g.group(1)!;
      out
        ..writeln()
        ..writeln('  @override')
        ..writeln('  String get $n => stretch(super.$n);');
      count++;
      continue;
    }
    final m = method.firstMatch(line);
    if (m != null) {
      final n = m.group(1)!;
      final params = m.group(2)!;
      final names = [
        for (final p in params.split(',').map((s) => s.trim()).where((s) => s.isNotEmpty)) p.split(RegExp(r'\s+')).last,
      ];
      out
        ..writeln()
        ..writeln('  @override')
        ..writeln('  String $n($params) => stretch(super.$n(${names.join(', ')}));');
      count++;
    }
  }
  out.writeln('}');
  File('test/helpers/pseudo_l10n.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote $count overrides to test/helpers/pseudo_l10n.dart');
}
